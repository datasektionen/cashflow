-- Cashflow 4.0 schema. Money is stored in öre (bigint), never as floats or numerics.

CREATE TABLE users (
    username        text PRIMARY KEY,           -- KTH ID, e.g. "turetek"
    name            text NOT NULL DEFAULT '',
    email           text NOT NULL DEFAULT '',
    bank_account    text NOT NULL DEFAULT '' CHECK (length(bank_account) <= 13),
    clearing_number text NOT NULL DEFAULT '' CHECK (length(clearing_number) <= 6),
    bank_name       text NOT NULL DEFAULT '' CHECK (length(bank_name) <= 30),
    created_at      timestamptz NOT NULL DEFAULT now()
);

-- A payment from the chapter to a member, covering one or more expenses.
-- Its bank tag is "Data" followed by the id.
CREATE TABLE payments (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer      text NOT NULL REFERENCES users,
    receiver   text NOT NULL REFERENCES users,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TYPE claim_kind AS ENUM ('expense', 'invoice');

-- Expenses and invoices are numbered separately, as in Cashflow 3. The number
-- is the public id: it appears in URLs and in Fortnox voucher descriptions.
CREATE SEQUENCE expense_number_seq;
CREATE SEQUENCE invoice_number_seq;

CREATE TABLE claims (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         claim_kind NOT NULL,
    number       bigint NOT NULL,
    owner        text NOT NULL REFERENCES users,
    description  text NOT NULL CHECK (description <> ''),
    created_at   timestamptz NOT NULL DEFAULT now(),
    -- Fortnox voucher, e.g. "E1234"; empty until accounted.
    verification text NOT NULL DEFAULT '' CHECK (length(verification) <= 7),

    -- Expense fields.
    expense_date date,
    confirmed_by text REFERENCES users,
    confirmed_at timestamptz,
    payment_id   bigint REFERENCES payments,
    flagged      boolean NOT NULL DEFAULT false,

    -- Invoice fields.
    invoice_number text,
    invoice_date   date,
    due_date       date,
    paid_by        text REFERENCES users,
    paid_at        timestamptz,

    UNIQUE (kind, number),
    CONSTRAINT expense_fields CHECK (
        kind <> 'expense' OR (
            expense_date IS NOT NULL
            AND invoice_number IS NULL AND invoice_date IS NULL AND due_date IS NULL
            AND paid_by IS NULL AND paid_at IS NULL
        )
    ),
    CONSTRAINT invoice_fields CHECK (
        kind <> 'invoice' OR (
            invoice_number IS NOT NULL
            AND expense_date IS NULL AND confirmed_by IS NULL AND confirmed_at IS NULL
            AND payment_id IS NULL AND NOT flagged
        )
    ),
    CONSTRAINT confirmed_together CHECK ((confirmed_by IS NULL) = (confirmed_at IS NULL)),
    CONSTRAINT paid_together CHECK ((paid_by IS NULL) = (paid_at IS NULL))
);

CREATE INDEX claims_owner_idx ON claims (owner);
CREATE INDEX claims_payment_idx ON claims (payment_id) WHERE payment_id IS NOT NULL;

-- A claim is split into parts, one per budget line. Attestation is per part,
-- since different cost centres attest their own parts.
CREATE TABLE claim_parts (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id              bigint NOT NULL REFERENCES claims ON DELETE CASCADE,
    position              int NOT NULL,
    cost_centre           text NOT NULL DEFAULT '',
    secondary_cost_centre text NOT NULL DEFAULT '',
    budget_line           text NOT NULL DEFAULT '',
    amount_ore            bigint NOT NULL,
    attested_by           text REFERENCES users,
    attested_at           timestamptz,
    UNIQUE (claim_id, position),
    CONSTRAINT attested_together CHECK ((attested_by IS NULL) = (attested_at IS NULL))
);

CREATE INDEX claim_parts_cost_centre_idx ON claim_parts (lower(cost_centre));

CREATE TABLE claim_files (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id     bigint NOT NULL REFERENCES claims ON DELETE CASCADE,
    storage_key  text NOT NULL UNIQUE,
    filename     text NOT NULL,
    content_type text NOT NULL,
    size_bytes   bigint NOT NULL,
    page_count   int,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX claim_files_claim_idx ON claim_files (claim_id);

CREATE TABLE comments (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id   bigint NOT NULL REFERENCES claims ON DELETE CASCADE,
    author     text NOT NULL REFERENCES users,
    body       text NOT NULL CHECK (body <> ''),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX comments_claim_idx ON comments (claim_id, created_at);

-- Workflow history, rendered and translated by the frontend. Cashflow 3 wrote
-- these as Swedish comments; migrated history stays in comments.
CREATE TYPE claim_event_type AS ENUM (
    'created', 'updated', 'attested', 'unattested', 'confirmed', 'unconfirmed',
    'flagged', 'unflagged', 'accounted', 'paid', 'reimbursed'
);

CREATE TABLE claim_events (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id   bigint NOT NULL REFERENCES claims ON DELETE CASCADE,
    actor      text NOT NULL REFERENCES users,
    type       claim_event_type NOT NULL,
    part_id    bigint REFERENCES claim_parts ON DELETE SET NULL,
    data       jsonb NOT NULL DEFAULT '{}',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX claim_events_claim_idx ON claim_events (claim_id, created_at);

-- The single Fortnox service account. Tokens are encrypted with AES-GCM.
CREATE TABLE fortnox_account (
    singleton        boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    authenticated_by text NOT NULL REFERENCES users,
    access_token     bytea NOT NULL,
    refresh_token    bytea NOT NULL,
    expires_at       timestamptz NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now()
);

-- Outbox for emails and retries, polled by a worker in the server process.
CREATE TABLE jobs (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       text NOT NULL,
    payload    jsonb NOT NULL,
    run_at     timestamptz NOT NULL DEFAULT now(),
    attempts   int NOT NULL DEFAULT 0,
    last_error text NOT NULL DEFAULT '',
    done_at    timestamptz
);

CREATE INDEX jobs_pending_idx ON jobs (run_at) WHERE done_at IS NULL;
