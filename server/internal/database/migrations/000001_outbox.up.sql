-- Emails waiting to be sent through spam, written in the same transaction as
-- the change that triggers them, so a failed send is retried rather than lost.
CREATE TABLE cashflow4_outbox (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payload    jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    run_at     timestamptz NOT NULL DEFAULT now(),
    attempts   int NOT NULL DEFAULT 0,
    last_error text NOT NULL DEFAULT '',
    sent_at    timestamptz
);

CREATE INDEX cashflow4_outbox_due_idx ON cashflow4_outbox (run_at) WHERE sent_at IS NULL;
